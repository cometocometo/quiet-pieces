import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
import { createServer } from 'vite';
const server = await createServer({ server: { port: 5192 }, logLevel: 'error' });
await server.listen();
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1360, height: 860 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:5192/?e2e'); await p.waitForSelector('.home'); await p.waitForTimeout(4000);
await p.screenshot({ path: 'tests/e2e/out/ph-home.png' });
console.log('daily:', await p.textContent('.daily-body h2'), '|', await p.textContent('.daily-body p'));
await p.click('.pack >> nth=0'); await p.waitForSelector('.grid .pic'); await p.waitForTimeout(2500);
await p.screenshot({ path: 'tests/e2e/out/ph-pack.png' });
await p.click('.grid .pic >> nth=0'); await p.waitForSelector('.setup'); await p.click('.counts button:has-text("48")'); await p.waitForTimeout(1500);
await p.screenshot({ path: 'tests/e2e/out/ph-setup.png' });
await p.click('button:has-text("Start puzzle")');
await p.waitForFunction(() => !document.querySelector('.loading') && window.__table, null, { timeout: 90000 });
if (await p.isVisible('button:has-text("Got it")')) await p.click('button:has-text("Got it")');
await p.waitForTimeout(2500);
await p.screenshot({ path: 'tests/e2e/out/ph-play.png' });
console.log('errors', errs);
await b.close(); await server.close();
